# Para los search URLs, necesitamos cambiar el formato de la URL completa
# de https://www.google.com/maps?cid=... a https://www.google.com/maps/search/?api=1&query=...
# Esto se hace con reemplazo de string

count = 0
for old, new in REPLACEMENTS:
    if old in content:
        if new.startswith('search'):
            # Reemplazar toda la URL de maps
            content = content.replace(
                'https://www.google.com/maps?' + old,
                'https://www.google.com/maps/' + new
            )
        else:
            content = content.replace(old, new)
        count += 1
        print(f'  ✓ {old} → {new}')
    else:
        print(f'  ✗ {old} → NO ENCONTRADO (ya reemplazado?)')

print(f'\nTotal: {count}/{len(REPLACEMENTS)} CIDs reemplazados')

